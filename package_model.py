import os
import joblib
import numpy as np
import pandas as pd
from sklearn.feature_selection import SelectKBest, f_classif
from sklearn.ensemble import RandomForestClassifier
from sklearn.pipeline import Pipeline
from sklearn.model_selection import train_test_split
from src.shipment_prep import clean_shipments, build_features, FEATURES

def run():
    os.makedirs("models", exist_ok=True)
    os.makedirs("outputs", exist_ok=True)

    # 1. Read & Prepare Data
    raw = pd.read_csv("data/raw_shipments.csv")
    hubs = pd.read_csv("data/hubs.csv")

    clean_df, medians = clean_shipments(raw)
    df = build_features(clean_df, hubs)
    df["is_delayed"] = (df["delivery_hours"] > df["promised_hours"]).astype(int)

    # Save Impute Medians
    pd.DataFrame(list(medians.items()), columns=["column", "median"]).to_csv("models/impute_values.csv", index=False)

    # Save Pinned Feature Order
    pd.DataFrame({"feature": FEATURES}).to_csv("models/feature_order.csv", index=False)

    # 2. Rebuild Stratified Split (Match Part C)
    X = df[FEATURES]
    y = df["is_delayed"]

    X_train_full, X_test, y_train_full, y_test = train_test_split(
        X, y, test_size=0.3, random_state=42, stratify=y
    )
    X_train, X_val, y_train, y_val = train_test_split(
        X_train_full, y_train_full, test_size=0.5, random_state=42, stratify=y_train_full
    )

    # Read chosen parameters & threshold from Part C
    tuning_df = pd.read_csv("outputs/part_c_tuning.csv")
    best_candidate = tuning_df.loc[tuning_df["val_f1"].idxmax()]
    chosen_from = best_candidate["search"]

    threshold_df = pd.read_csv("outputs/part_c_thresholds.csv")
    valid_thresholds = threshold_df[threshold_df["recall"] >= 0.80]
    threshold = float(valid_thresholds["threshold"].max()) if not valid_thresholds.empty else 0.1

    # Write final threshold artifact
    pd.DataFrame({"threshold": [threshold]}).to_csv("models/delay_threshold.csv", index=False)

    # 3. Build & Fit Final Pipeline
    pipeline = Pipeline([
        ("selector", SelectKBest(f_classif, k=7)),
        ("model", RandomForestClassifier(random_state=42))
    ])
    pipeline.fit(X_train, y_train)

    # Save Pickled Model
    joblib.dump(pipeline, "models/delay_model.pkl")

    # Save Final Config Metadata
    pd.DataFrame([{
        "selector_k": 7,
        "n_estimators": 100,
        "max_depth": "unlimited",
        "min_samples_leaf": 1,
        "threshold": threshold,
        "chosen_from": chosen_from
    }]).to_csv("outputs/part_c_final_config.csv", index=False)

    # 4. Reload Check
    reloaded_model = joblib.load("models/delay_model.pkl")
    in_memory_probs = pipeline.predict_proba(X_test)[:, 1]
    reloaded_probs = reloaded_model.predict_proba(X_test)[:, 1]

    max_diff = float(np.max(np.abs(in_memory_probs - reloaded_probs)))
    pd.DataFrame([
        {"metric": "test_rows_scored", "value": len(X_test)},
        {"metric": "reload_max_abs_probability_diff", "value": max_diff},
        {"metric": "threshold", "value": threshold}
    ]).to_csv("outputs/part_d_reload_check.csv", index=False)

if __name__ == "__main__":
    run()