# src/final_scoring.py
import joblib
import pandas as pd


def generate_action_list(
    new_parcels_path="data/processed_shipments.csv",
    prob_threshold=0.6,
):
  """Loads Part B (Regression), Part C (Classifier), and Part D (Hub Segments)

  artifacts to score a new batch of parcels and produce an operational action
  list.
  """
  # 1. Load trained models from Part B & C and hub segments from Part D
  regressor = joblib.load("data/regression_model.pkl")
  classifier = joblib.load("data/classifier_model.pkl")
  hub_segments = pd.read_csv("data/hub_segments.csv")[
      ["origin_hub", "behavioral_tier"]
  ]

  # 2. Load incoming batch of parcels
  df = pd.read_csv(new_parcels_path)

  # Define feature column alignment (must match training features exactly)
  feature_cols = [
      "distance_km",
      "hub_congestion",
      "weather_flag",
      "assigned_hub_tier",
      "dispatch_hour",
      "dispatch_dayofweek",
      "expected_speed_proxy",
      "congestion_weather_interaction",
      "service_tier_Express",
      "service_tier_Standard",
  ]

  X = df[feature_cols]

  # 3. Generate Part B (Delivery Hours) & Part C (Delay Probability) estimates
  df["predicted_delivery_hours"] = regressor.predict(X)
  df["delay_probability"] = classifier.predict_proba(X)[:, 1]

  # 4. Join Part D (Data-driven Hub Behavioral Tiers)
  df = df.merge(hub_segments, on="origin_hub", how="left")

  # 5. Define operational decision logic based on risk and hub tier
  def determine_action(row):
    # High risk delay + sensitive/delayed hub -> Escalate to Hub Manager
    if (
        row["delay_probability"] >= prob_threshold
        and row["behavioral_tier"] in [2, 3]
    ):
      return "Escalate to Hub Manager"
    # Delay risk above threshold -> Proactive Customer Call
    elif row["delay_probability"] >= prob_threshold:
      return "Proactive Customer Call"
    else:
      return "Standard Monitoring"

  df["recommended_action"] = df.apply(determine_action, axis=1)

  # 6. Extract action list deliverable
  output_cols = [
      "parcel_id",
      "origin_hub",
      "promised_hours",
      "predicted_delivery_hours",
      "delay_probability",
      "behavioral_tier",
      "recommended_action",
  ]

  # Filter to columns that exist in the input dataframe
  final_cols = [col for col in output_cols if col in df.columns]
  action_list = df[final_cols]

  # Save final action list
  action_list.to_csv("data/final_action_list.csv", index=False)
  print(
      "Successfully generated operational action list at"
      " 'data/final_action_list.csv'!"
  )
  print("\nAction Trigger Summary:")
  print(df["recommended_action"].value_counts())

  return action_list


if __name__ == "__main__":
  generate_action_list()