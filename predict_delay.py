import os
import joblib
import pandas as pd
from src.shipment_prep import clean_shipments, build_features

def run():
    os.makedirs("outputs", exist_ok=True)

    # 1. Load Data & Saved Artifacts
    new_raw = pd.read_csv("data/new_shipments.csv")
    hubs = pd.read_csv("data/hubs.csv")
    hub_segments = pd.read_csv("outputs/hub_segments.csv")

    impute_df = pd.read_csv("models/impute_values.csv")
    medians = dict(zip(impute_df["column"], impute_df["median"]))

    feature_order = pd.read_csv("models/feature_order.csv")["feature"].tolist()
    threshold = pd.read_csv("models/delay_threshold.csv")["threshold"].iloc[0]
    model = joblib.load("models/delay_model.pkl")

    # 2. Preprocess using shared functions & stored medians
    clean_df, _ = clean_shipments(new_raw, medians=medians)
    featured_df = build_features(clean_df, hubs)

    # Arrange columns in exact training order
    X_new = featured_df[feature_order]

    # 3. Predict & Flag Delays
    delay_probs = model.predict_proba(X_new)[:, 1]
    featured_df["delay_probability"] = delay_probs.round(4)
    featured_df["flagged"] = (featured_df["delay_probability"] >= threshold).astype(int)

    # 4. Join Segments & Assign Action Rules
    res = featured_df.merge(hub_segments[["hub_id", "segment"]], on="hub_id", how="left")

    def assign_action(row):
        if row["flagged"] == 1:
            if row["segment"] == "Escalate":
                return "Escalate to hub manager"
            return "Proactive customer call"
        return "No action"

    res["action"] = res.apply(assign_action, axis=1)

    # 5. Export Output
    output_cols = ["shipment_id", "hub_id", "segment", "delay_probability", "flagged", "action"]
    res[output_cols].to_csv("outputs/new_shipment_actions.csv", index=False)

if __name__ == "__main__":
    run()