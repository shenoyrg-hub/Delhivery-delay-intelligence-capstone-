def clean_shipments(raw: pd.DataFrame, medians: dict = None):
    """
    Cleans raw shipments DataFrame following the 7-step pipeline.

    Parameters:
    -----------
    raw : pd.DataFrame
        Raw shipments table.
    medians : dict, optional
        Dictionary containing pre-computed medians for 'distance_km',
        'parcel_weight_kg', and 'declared_value_inr'.

    Returns:
    --------
    tuple : (clean_df, medians_dict)
    """
    df = raw.copy()

    # Step 1: Drop exact duplicate rows
    df = df.drop_duplicates().reset_index(drop=True)

    # Step 2: Clean service_type (strip spaces, convert to title case)
    if "service_type" in df.columns:
        df["service_type"] = df["service_type"].astype(str).str.strip().str.title()

    # Step 3: Replace missing payment_mode with "Unknown"
    if "payment_mode" in df.columns:
        df["payment_mode"] = df["payment_mode"].fillna("Unknown")

    # Step 4: Parse declared_value (strip ₹ and commas -> declared_value_inr)
    if "declared_value" in df.columns:
        df["declared_value_inr"] = (
            df["declared_value"]
            .astype(str)
            .str.replace("₹", "", regex=False)
            .str.replace(",", "", regex=False)
        )
        df["declared_value_inr"] = pd.to_numeric(df["declared_value_inr"], errors="coerce")
        df = df.drop(columns=["declared_value"])

    # Step 5: Convert dispatch_time to datetime
    if "dispatch_time" in df.columns:
        df["dispatch_time"] = pd.to_datetime(df["dispatch_time"])

    # Step 6: Scanner-fault sentinel for parcel_weight_kg > 100 -> NaN
    if "parcel_weight_kg" in df.columns:
        df.loc[df["parcel_weight_kg"] > 100, "parcel_weight_kg"] = np.nan

    # Step 7: Fill missing values with median
    if medians is None:
        medians = {
            "distance_km": float(df["distance_km"].median()),
            "parcel_weight_kg": float(df["parcel_weight_kg"].median()),
            "declared_value_inr": float(df["declared_value_inr"].median())
        }

    df["distance_km"] = df["distance_km"].fillna(medians["distance_km"])
    df["parcel_weight_kg"] = df["parcel_weight_kg"].fillna(medians["parcel_weight_kg"])
    df["declared_value_inr"] = df["declared_value_inr"].fillna(medians["declared_value_inr"])

    return df, medians


def build_features(clean: pd.DataFrame, hubs: pd.DataFrame) -> pd.DataFrame:
    """
    Attaches hub info via left merge and constructs required modelling features.

    Parameters:
    -----------
    clean : pd.DataFrame
        Cleaned shipments table returned by clean_shipments.
    hubs : pd.DataFrame
        Hub metadata table (hubs.csv).

    Returns:
    --------
    pd.DataFrame containing hub info and engineered features.
    """
    df = clean.copy()

    # Left merge with hubs metadata
    df = df.merge(
        hubs[["hub_id", "hub_city", "region", "hub_tier", "hub_daily_capacity"]],
        on="hub_id",
        how="left"
    )

    # Feature Engineering
    df["promised_hours"] = df["service_type"].map(PROMISED_HOURS).astype(int)
    df["is_cod"] = (df["payment_mode"] == "COD").astype(int)
    df["is_weekend"] = df["dispatch_time"].dt.dayofweek.isin([5, 6]).astype(int)
    df["dispatch_hour"] = df["dispatch_time"].dt.hour.astype(int)
    df["log_declared_value"] = np.log(df["declared_value_inr"])

    return df